export function Icon({ name, className, style }: { name: string; className?: string; style?: React.CSSProperties }) {
  const C = MAP[name] ?? Sparkles;
  return <C className={className} style={style} />;
}

export function CategoryBubble({ icon, color, size = 40 }: { icon: string; color: string; size?: number }) {
  return (
    <span className="inline-flex shrink-0 items-center justify-center rounded-2xl" style={{ width: size, height: size, background: `${color}1A`, color }}>
      <Icon name={icon} style={{ width: size * 0.5, height: size * 0.5 }} />
    </span>
  );
}
